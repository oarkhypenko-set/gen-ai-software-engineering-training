"""/transactions endpoints."""

from datetime import datetime, timezone

from flask import Blueprint, Response, jsonify, request, url_for

from src.models import Transaction
from src.utils.helpers import (
    error_response,
    filter_transactions,
    get_store,
    has_sufficient_funds,
    parse_filters,
    transactions_to_csv,
    validation_error,
)
from src.validators import validate_transaction

transactions_bp = Blueprint("transactions", __name__, url_prefix="/transactions")


@transactions_bp.post("")
def create_transaction():
    payload = request.get_json(silent=True)
    if payload is None:
        return validation_error([{"field": "body", "message": "Request body must be valid JSON"}])

    errors = validate_transaction(payload)
    if errors:
        return validation_error(errors)

    # Only client-controlled fields are copied; id, timestamp and status are
    # always generated by the server.
    transaction = Transaction(
        amount=float(payload["amount"]),
        currency=payload["currency"].upper(),
        type=payload["type"],
        from_account=payload.get("fromAccount"),
        to_account=payload.get("toAccount"),
    )

    # Money leaving an account must not make its balance negative. Such
    # transactions are still recorded, but as "failed", so they never affect
    # balances. The lock keeps concurrent requests from both passing the check.
    store = get_store()
    with store.atomic():
        if transaction.from_account and not has_sufficient_funds(
            store.all(), transaction.from_account, transaction.currency, transaction.amount
        ):
            transaction.status = "failed"
        store.add(transaction)

    response = jsonify(transaction.to_dict())
    response.status_code = 201
    response.headers["Location"] = url_for(".get_transaction", transaction_id=transaction.id)
    return response


@transactions_bp.get("")
def list_transactions():
    filters, errors = parse_filters(request.args)
    if errors:
        return validation_error(errors, error="Invalid query parameters")

    transactions = filter_transactions(get_store().all(), filters)
    return jsonify([tx.to_dict() for tx in transactions])


EXPORT_FORMATS = ("csv",)


# Defined before /<transaction_id> for readability; Werkzeug already matches
# the static "/export" path ahead of the variable one.
@transactions_bp.get("/export")
def export_transactions():
    export_format = request.args.get("format", "csv").lower()
    errors = []
    if export_format not in EXPORT_FORMATS:
        errors.append({"field": "format",
                       "message": f"format must be one of: {', '.join(EXPORT_FORMATS)}"})
    filters, filter_errors = parse_filters(request.args)
    errors += filter_errors
    if errors:
        return validation_error(errors, error="Invalid query parameters")

    transactions = filter_transactions(get_store().all(), filters)
    filename = f"transactions-{datetime.now(timezone.utc):%Y%m%d-%H%M%S}.csv"
    return Response(
        transactions_to_csv(transactions),
        mimetype="text/csv",
        headers={"Content-Disposition": f'attachment; filename="{filename}"'},
    )


@transactions_bp.get("/<transaction_id>")
def get_transaction(transaction_id: str):
    transaction = get_store().get(transaction_id)
    if transaction is None:
        return error_response(404, f"Transaction '{transaction_id}' not found")
    return jsonify(transaction.to_dict())
